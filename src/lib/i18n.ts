export type Locale = "ar" | "en";
const STORAGE_KEY = "ck.uiLocale";

type LocaleListener = (locale: Locale) => void;
const listeners = new Set<LocaleListener>();

function readStoredLocale(): Locale {
  if (typeof window === "undefined") return "ar";
  const v = localStorage.getItem(STORAGE_KEY);
  return v === "en" || v === "ar" ? v : "ar";
}

let currentLocale: Locale = readStoredLocale();

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale) {
  if (currentLocale === locale) return;
  currentLocale = locale;
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  }
  listeners.forEach((fn) => fn(locale));
}

export function subscribeLocale(listener: LocaleListener): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function t(key: string): string {
  if (currentLocale === "en") return key;
  return ar[key] ?? key;
}

export function tPartial(text: string): string {
  if (currentLocale === "en") return text;
  if (ar[text]) return ar[text];
  let out = text;
  const keys = Object.keys(ar).sort((a, b) => b.length - a.length);
  for (const k of keys) {
    if (out.includes(k)) out = out.split(k).join(ar[k]!);
  }
  return out;
}

if (typeof window !== "undefined") {
  document.documentElement.lang = currentLocale;
  document.documentElement.dir = currentLocale === "ar" ? "rtl" : "ltr";
}
